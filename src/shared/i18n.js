/** Choisit la langue : préférence, puis langue du système, puis français. */
function resolveLanguage(pref, systemLocale) {
  if (pref === 'fr' || pref === 'en') return pref;
  return /^en/i.test(String(systemLocale || '')) ? 'en' : 'fr';
}

/** Traduit une clé ; `{x}` est remplacé par params.x ; « a|b » = singulier|pluriel selon params.n. */
function translate(lang, key, params) {
  const dict = DICTS[lang] || DICTS.fr;
  let s = dict[key];
  if (s === undefined) s = DICTS.fr[key];
  if (s === undefined) return key;
  if (params && s.includes('|') && typeof params.n === 'number') {
    const [one, many] = s.split('|');
    s = lang === 'fr' ? (params.n < 2 ? one : many) : params.n === 1 ? one : many;
  }
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
  return s;
}

module.exports = { DICTS, resolveLanguage, translate };
